// Renders every exercise motion into one sprite atlas (row per exercise, FRAMES columns) used for
// animated thumbnails, plus an optional labelled contact sheet for reviewing poses.
//   npm run sprites                 -> public/sprites/exercises.png + src/data/spriteIndex.ts
//   npm run sprites -- --contact    -> also /tmp/vitalime-contact.png
import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { runnerImport } from "vite";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const FRAMES = 8;
const CELL = 96;

const { module: motions } = await runnerImport("/src/data/motions.ts", { root, configFile: false });
const { module: pose } = await runnerImport("/src/lib/pose.ts", { root, configFile: false });

const ids = Object.keys(motions.MOTIONS).sort();
const svgFor = (id, t, size) => Buffer.from(pose.motionSvg(motions.MOTIONS[id], t, { size }));

const composites = [];
for (const [row, id] of ids.entries()) {
  for (let i = 0; i < FRAMES; i++) {
    composites.push({ input: svgFor(id, i / FRAMES, CELL), left: i * CELL, top: row * CELL });
  }
}
await mkdir(`${root}public/sprites`, { recursive: true });
await sharp({ create: { width: FRAMES * CELL, height: ids.length * CELL, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .png({ compressionLevel: 9, palette: true, quality: 90 })
  .toFile(`${root}public/sprites/exercises.png`);

await writeFile(
  `${root}src/data/spriteIndex.ts`,
  `// Generated by scripts/generate-sprites.mjs — do not edit.\n` +
    `export const SPRITE_FRAMES = ${FRAMES};\n` +
    `export const SPRITE_ROWS: Record<string, number> = ${JSON.stringify(Object.fromEntries(ids.map((id, i) => [id, i])), null, 2)};\n`,
);
console.log(`sprites: ${ids.length} exercises × ${FRAMES} frames`);

if (process.argv.includes("--contact")) {
  const COLS = 2;
  const SIZE = 190;
  const PHASES = [0, 0.25, 0.5, 0.75];
  const tile = SIZE * PHASES.length + 10;
  const rows = Math.ceil(ids.length / COLS);
  const items = [];
  for (const [n, id] of ids.entries()) {
    const x0 = (n % COLS) * tile;
    const y0 = Math.floor(n / COLS) * (SIZE + 22);
    PHASES.forEach((t, i) =>
      items.push({ input: Buffer.from(pose.motionSvg(motions.MOTIONS[id], t, { size: SIZE, background: "#111113" })), left: x0 + i * SIZE, top: y0 + 20 }),
    );
    items.push({
      input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${tile}" height="20"><text x="4" y="15" font-family="Helvetica" font-size="14" fill="#c6ff3d">${id}</text></svg>`),
      left: x0,
      top: y0,
    });
  }
  await sharp({ create: { width: COLS * tile, height: rows * (SIZE + 22), channels: 4, background: "#050505" } })
    .composite(items)
    .png()
    .toFile("/tmp/vitalime-contact.png");
  const pageRows = 4;
  const pageH = pageRows * (SIZE + 22);
  for (let p = 0; p * pageH < rows * (SIZE + 22); p++) {
    await sharp("/tmp/vitalime-contact.png")
      .extract({ left: 0, top: p * pageH, width: COLS * tile, height: Math.min(pageH, rows * (SIZE + 22) - p * pageH) })
      .toFile(`/tmp/vitalime-contact-${p}.png`);
  }
  console.log("contact sheet: /tmp/vitalime-contact-*.png");
}
